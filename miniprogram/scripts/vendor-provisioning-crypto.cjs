// Reproducible mechanical CommonJS conversion; no cryptographic source edits.
const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto')
const { execFileSync } = require('node:child_process')
const ts = require('typescript')
const archive = process.argv[2]
if (!archive || process.argv.length !== 3) throw Error('Pass the official ciphers-2.4.0.tgz archive')
const expected = 'AnjFn0Jv92laAkvMrghlFZq4qQCIN/4DxFV/eooqtC2YTjB7kBeLMS2T9KJX4Dn+ZVXLOwK0lSgqDtx9gvxtiw=='
if (crypto.createHash('sha512').update(fs.readFileSync(archive)).digest('base64') !== expected) throw Error('Vendor archive integrity mismatch')
const read = name => execFileSync('tar', ['-xOf', archive, 'package/' + name], { maxBuffer: 2 * 1024 * 1024 }).toString('utf8')
const pkg = JSON.parse(read('package.json'))
if (pkg.name !== '@noble/ciphers' || pkg.version !== '2.4.0' || pkg.license !== 'MIT') throw Error('Unexpected vendor metadata')
const target = path.resolve(__dirname, '../vendor/noble-ciphers-2.4.0')
fs.mkdirSync(target, { recursive: true })
const manifest = { package: '@noble/ciphers', version: pkg.version, license: 'MIT', gitHead: pkg.gitHead || 'd9e8a6a599e7ed729d9be03854c46a3c73bd9a79',
  source: 'https://registry.npmjs.org/@noble/ciphers/-/ciphers-2.4.0.tgz', integrity: 'sha512-' + expected, files: {} }
for (const name of ['aes', '_polyval', 'utils']) {
  const source = read(name + '.js')
  const converted = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2019, removeComments: false } }).outputText
    .replace(/require\("\.\/([^"/]+)\.js"\)/g, 'require("./$1")')
  const output = '// @ts-nocheck\n// Generated by scripts/vendor-provisioning-crypto.cjs from unmodified official JS.\n' + converted
  fs.writeFileSync(path.join(target, name + '.ts'), output)
  manifest.files[name + '.ts'] = { originalSHA256: crypto.createHash('sha256').update(source).digest('hex'), generatedSHA256: crypto.createHash('sha256').update(output).digest('hex') }
}
fs.writeFileSync(path.join(target, 'LICENSE'), read('LICENSE'))
fs.writeFileSync(path.join(target, 'SOURCE.json'), JSON.stringify(manifest, null, 2) + '\n')
console.log('Vendored @noble/ciphers 2.4.0 (verified official archive; mechanical CJS conversion only)')
